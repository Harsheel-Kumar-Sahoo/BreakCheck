import type { ImpactReport } from "./analyze";

const LABEL: Record<string, string> = {
  safe_to_ship: "✅ Safe to ship",
  ship_with_caution: "⚠️ Ship with caution",
  do_not_ship: "🛑 Do not ship",
};

export interface ReportMeta { project: string; from: string; to: string; verdict: string; reason: string }

// Full report: for docs, wikis, tickets.
export function buildMarkdown(r: ImpactReport, m: ReportMeta): string {
  const lines: string[] = [];
  lines.push(`# BreakCheck report: ${m.project} ${m.from} → ${m.to}`, "");
  lines.push(`**Verdict:** ${LABEL[m.verdict] ?? m.verdict}`, `> ${m.reason}`, "");
  const s = r.summary;
  lines.push(`- Affected consumers: ${s.affectedConsumers} / ${s.totalConsumers}`);
  lines.push(`- Breaking changes: ${s.breakingChanges} (hits on consumers: ${s.breakingHits}, used by nobody: ${s.breakingNobodyUses})`);
  lines.push(`- Potentially breaking changes: ${s.potentialChanges}`, "");

  lines.push("## Consumers", "");
  lines.push("| Consumer | Owner | Breaking | Potential |", "|---|---|---|---|");
  for (const c of r.consumers) lines.push(`| ${c.name} | ${c.owner || "-"} | ${c.breaking} | ${c.potential} |`);
  lines.push("");

  const byId = new Map(r.columns.map((c) => [c._id, c]));
  for (const c of r.consumers.filter((x) => x.breaking + x.potential > 0)) {
    lines.push(`### ${c.name}`, "");
    for (const [id, sev] of Object.entries(c.hits)) {
      const ch = byId.get(id);
      if (ch) lines.push(`- **${sev}**: ${ch.title}, \`${ch.method} ${ch.path}\`${ch.target ? ` (\`${ch.target}\`)` : ""}`);
    }
    lines.push("");
  }
  const clean = r.consumers.filter((c) => c.breaking + c.potential === 0).map((c) => c.name);
  if (clean.length) lines.push(`Not affected: ${clean.join(", ")}`, "");
  lines.push("_Generated by BreakCheck (Team Almost Avengers)_");
  return lines.join("\n");
}

// Short version, shaped for a GitHub pull-request comment.
export function buildPrComment(r: ImpactReport, m: ReportMeta): string {
  const s = r.summary;
  const out: string[] = [];
  out.push(`## BreakCheck: ${LABEL[m.verdict] ?? m.verdict}`, "");
  out.push(`**${m.project}** \`${m.from}\` → \`${m.to}\`: ${m.reason}`, "");
  out.push(`| Breaking changes | Hit consumers | Potential | Affected consumers |`, `|---|---|---|---|`);
  out.push(`| ${s.breakingChanges} | ${s.breakingHits} | ${s.potentialChanges} | ${s.affectedConsumers}/${s.totalConsumers} |`, "");
  const hit = r.consumers.filter((c) => c.breaking > 0);
  if (hit.length) {
    out.push("<details><summary>Who breaks</summary>", "");
    for (const c of hit) out.push(`- **${c.name}** (${c.owner || "no owner"}): ${c.breaking} breaking, ${c.potential} potential`);
    out.push("", "</details>", "");
  }
  out.push("<sub>BreakCheck · deterministic rules, no LLM</sub>");
  return out.join("\n");
}